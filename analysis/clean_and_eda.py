from pathlib import Path
import json
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data"

customers = pd.read_csv(DATA_DIR / "customers.csv")
products = pd.read_csv(DATA_DIR / "products.csv")
orders = pd.read_csv(DATA_DIR / "orders.csv")




print("Customers shape:", customers.shape)
print("Products shape:", products.shape)
print("Orders shape:", orders.shape)

print("\nCustomers:")
print(customers.head())

print("\nProducts:")
print(products.head())

print("\nOrders:")
print(orders.head())

print("\nOrders data types:")
print(orders.dtypes)

print("\nMissing values in orders:")
print(orders.isnull().sum())

"""**TASK 2 - Standardize payment_method casing**"""

orders_raw = orders.copy()

print("Original payment-method values:")
print(orders_raw["payment_method"].unique())

print("Payment methods before cleaning:")
print(orders["payment_method"].value_counts())

orders["payment_method"] = (
    orders["payment_method"]
    .str.strip()
    .str.upper()
)

print("\nPayment methods after cleaning:")
print(orders["payment_method"].value_counts())

print("\nUnique payment methods:",
      orders["payment_method"].nunique())

"""**Task 3 — Remove duplicate orders**"""

natural_key = [
    "customer_id",
    "product_id",
    "order_date",
    "quantity",
    "discount_pct",
    "payment_method",
    "rating",
    "returned"
]


duplicate_mask = orders.duplicated(
    subset=natural_key,
    keep="first"
)


dropped_order_ids = orders.loc[duplicate_mask, "order_id"].tolist()
print("Duplicate rows detected:", duplicate_mask.sum())
print("Dropped order IDs:", dropped_order_ids)

orders_clean = orders.loc[~duplicate_mask].copy()

print("Cleaned orders shape:", orders_clean.shape)

"""**Task 4 — Impute missing values**"""

missing_discount = orders_clean["discount_pct"].isnull().sum()
missing_rating = orders_clean["rating"].isnull().sum()

print("Missing discounts before imputation:", missing_discount)
print("Missing ratings before imputation:", missing_rating)


orders_clean["discount_pct"] = orders_clean["discount_pct"].fillna(0)

median_rating = orders_clean["rating"].median()
print("Median rating before imputation:", median_rating)

orders_clean["rating"] = orders_clean["rating"].fillna(median_rating)
print("Missing discounts after imputation:",
      orders_clean["discount_pct"].isnull().sum())
print("Missing ratings after imputation:",
      orders_clean["rating"].isnull().sum())

"""**Task 5 — Merge and reconcile against Part 1**"""

merged_orders = orders_clean.merge(
    products,
    on="product_id",
    how="left"
)

merged_orders = merged_orders.merge(
    customers,
    on="customer_id",
    how="left"
)


merged_orders["order_value"] = (
    merged_orders["quantity"]
    * merged_orders["price"]
    * (1 - merged_orders["discount_pct"] / 100)
)


cleaned_total_revenue = merged_orders["order_value"].sum()

print("Cleaned order rows:", len(merged_orders))
print(f"Cleaned total revenue: Rs. {cleaned_total_revenue:.2f}")


raw_sql_revenue = 99860.20
revenue_difference = raw_sql_revenue - cleaned_total_revenue

print(f"Raw SQL revenue: Rs. {raw_sql_revenue:.2f}")
print(f"Revenue difference: Rs. {revenue_difference:.2f}")


dropped_orders = orders.loc[
    orders["order_id"].isin(dropped_order_ids)
].copy()

dropped_orders = dropped_orders.merge(
    products[["product_id", "price"]],
    on="product_id",
    how="left"
)


dropped_orders["discount_pct"] = dropped_orders["discount_pct"].fillna(0)

dropped_orders["order_value"] = (
    dropped_orders["quantity"]
    * dropped_orders["price"]
    * (1 - dropped_orders["discount_pct"] / 100)
)

dropped_rows_value = dropped_orders["order_value"].sum()

print(f"Dropped duplicate rows: {len(dropped_orders)}")
print(f"Value of dropped rows: Rs. {dropped_rows_value:.2f}")


print(
    "\nReconciliation: The cleaned total revenue is lower than the raw SQL "
    "total because five duplicate orders were removed in Task 3. The "
    f"independently calculated value of those duplicate rows is "
    f"Rs. {dropped_rows_value:.2f}, which explains the revenue difference "
    f"of Rs. {revenue_difference:.2f}. Imputing missing discounts and "
    "ratings does not change order value because missing discounts are "
    "filled with zero and ratings are not used in the calculation."
)

"""**Task 6 — IQR outlier detection on quantity**"""

Q1 = merged_orders["quantity"].quantile(0.25)
Q3 = merged_orders["quantity"].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Lower bound:", lower_bound)
print("Upper bound:", upper_bound)


outliers = merged_orders[
    (merged_orders["quantity"] < lower_bound) |
    (merged_orders["quantity"] > upper_bound)
]

print("\nQuantity outliers:")
print(outliers[["order_id", "quantity"]])

print("\nNumber of outlier rows:", len(outliers))

"""**Task 7 — Hypothesis: does COD have a higher return rate?**"""

return_analysis = orders_clean.groupby("payment_method")["returned"].agg(
    total_orders="count",
    returned_orders="sum",
    return_rate="mean"
)

return_analysis["return_rate_pct"] = (
    return_analysis["return_rate"] * 100
).round(1)

print(return_analysis[["total_orders", "returned_orders", "return_rate_pct"]])


cod_rate = return_analysis.loc["COD", "return_rate_pct"]
card_rate = return_analysis.loc["CARD", "return_rate_pct"]
upi_rate = return_analysis.loc["UPI", "return_rate_pct"]

if cod_rate > card_rate and cod_rate > upi_rate:
    print("\nHypothesis: CONFIRMED")
    print("COD has the highest return rate.")
else:
    print("\nHypothesis: NOT CONFIRMED")
    print("COD does not have the highest return rate.")

"""**Task 8 — Multi-level segmentation**"""

orders_segmented = orders_clean.merge(
    customers[["customer_id", "city_tier"]],
    on="customer_id",
    how="left"
)

segment_analysis = orders_segmented.groupby(
    ["payment_method", "city_tier"]
)["returned"].agg(
    total_orders="count",
    returned_orders="sum",
    return_rate="mean"
)

segment_analysis["return_rate_pct"] = (
    segment_analysis["return_rate"] * 100
).round(1)

print(segment_analysis[
    ["total_orders", "returned_orders", "return_rate_pct"]
])


highest_risk = segment_analysis["return_rate_pct"].idxmax()
highest_rate = segment_analysis["return_rate_pct"].max()

print("\nHighest-risk segment:")
print("Payment method:", highest_risk[0])
print("City tier:", highest_risk[1])
print("Return rate:", highest_rate, "%")

"""**Task 9 — Correlation analysis**"""

corr_cols = ["rating", "returned", "discount_pct", "quantity"]
correlation_matrix = orders_clean[corr_cols].corr()

print("Correlation matrix:")
print(correlation_matrix.round(2))

def correlation_band(value):
    value = abs(value)

    if value < 0.20:
        return "Negligible"
    elif value < 0.40:
        return "Weak"
    elif value < 0.70:
        return "Moderate"
    else:
        return "Strong"

print("\nCorrelation strength for each pair:")

for i in range(len(corr_cols)):
    for j in range(i + 1, len(corr_cols)):
        var1 = corr_cols[i]
        var2 = corr_cols[j]
        value = correlation_matrix.loc[var1, var2]

        print(
            f"{var1} vs {var2}: {value:.2f} "
            f"({correlation_band(value)})"
        )


discount_return_corr = correlation_matrix.loc["discount_pct", "returned"]

print("\nDiscount vs returned correlation:", round(discount_return_corr, 2))

if discount_return_corr <= -0.20:
    print("Conclusion: Evidence of a negative correlation.")
else:
    print("Conclusion: BUSTED — no meaningful negative correlation.")

"""**Task 10 — Outlier-corrected monthly revenue trend**"""

orders_clean["order_date"] = pd.to_datetime(orders_clean["order_date"])
orders_clean["year_month"] = orders_clean["order_date"].dt.to_period("M")

monthly_data = orders_clean.merge(
    products[["product_id", "price"]],
    on="product_id",
    how="left"
)

monthly_data["order_value"] = (
    monthly_data["quantity"]
    * monthly_data["price"]
    * (1 - monthly_data["discount_pct"] / 100)
)

outlier_ids = outliers["order_id"].tolist()

monthly_revenue_all = (
    monthly_data.groupby("year_month")["order_value"]
    .sum()
    .round(2)
)

monthly_revenue_corrected = (
    monthly_data[~monthly_data["order_id"].isin(outlier_ids)]
    .groupby("year_month")["order_value"]
    .sum()
    .round(2)
)

monthly_comparison = pd.DataFrame({
    "Revenue_Including_Outliers": monthly_revenue_all,
    "Revenue_Excluding_Outliers": monthly_revenue_corrected
}).fillna(0)

print("Monthly revenue comparison (INR):")
print(monthly_comparison)

peak_month_all = monthly_revenue_all.idxmax()
peak_month_corrected = monthly_revenue_corrected.idxmax()

print("\nPeak month including outliers:", peak_month_all)
print("Peak month excluding outliers:", peak_month_corrected)
print(
    "January revenue including outliers:",
    monthly_revenue_all.get(pd.Period("2026-01"), 0)
)
print(
    "January revenue excluding outliers:",
    monthly_revenue_corrected.get(pd.Period("2026-01"), 0)
)
print(
    "March revenue excluding outliers:",
    monthly_revenue_corrected.get(pd.Period("2026-03"), 0)
)

print(
    "\nConclusion: January 2026's apparent revenue lead is inflated "
    "by two unusually large quantity orders: O0011 on 2026-01-28 "
    "and O0098 on 2026-01-10. After excluding these two outliers "
    "for comparison, March 2026 is the genuine peak month, with "
    "revenue of ₹20,318.90. The outliers are flagged for analysis "
    "and are not permanently removed from the cleaned dataset."
)

cleaned_data_path = DATA_DIR / "cleaned_data.csv"

orders_clean.to_csv(cleaned_data_path, index=False)

print(f"\nCleaned data exported to: {cleaned_data_path}")
print("Cleaned data shape:", orders_clean.shape)


